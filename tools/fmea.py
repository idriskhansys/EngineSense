#!/usr/bin/env python3
"""Failure-mode ranking: reads docs/fmea.csv, validates it against the code base and writes docs/fmea.md.

RPN = Severity x Occurrence x Detection (each 1-10, 10 = worst). Detection is scored twice: before the
mitigation existed (D_before) and with the implemented design (D_after).
"""
import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load():
    with open(ROOT / "docs" / "fmea.csv", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def validate(rows):
    errors = []
    scen_src = (ROOT / "core" / "src" / "scenarios.cpp").read_text(encoding="utf-8")
    scenarios = set(re.findall(r'add\(\s*"(\w+)"', scen_src))
    reqs = set(re.findall(r"^\|\s*(REQ-[A-Z]+-\d+)\s*\|", (ROOT / "docs" / "requirements.md").read_text(encoding="utf-8"), re.M))
    for r in rows:
        for key in ("S", "O", "D_before", "D_after"):
            if not 1 <= int(r[key]) <= 10:
                errors.append(f"{r['id']}: {key} out of range 1..10")
        if int(r["D_after"]) > int(r["D_before"]):
            errors.append(f"{r['id']}: D_after worse than D_before")
        for s in filter(None, r["scenario"].split(";")):
            if s not in scenarios:
                errors.append(f"{r['id']}: unknown scenario '{s}'")
        for q in filter(None, r["requirement"].split(";")):
            if q not in reqs:
                errors.append(f"{r['id']}: unknown requirement '{q}'")
    return errors


def render(rows):
    for r in rows:
        r["rpn_before"] = int(r["S"]) * int(r["O"]) * int(r["D_before"])
        r["rpn_after"] = int(r["S"]) * int(r["O"]) * int(r["D_after"])
    rows = sorted(rows, key=lambda r: -r["rpn_before"])
    total_b = sum(r["rpn_before"] for r in rows)
    total_a = sum(r["rpn_after"] for r in rows)
    out = ["# Failure Mode and Effects Analysis (FMEA)", "",
           "_Generated by `tools/fmea.py` from `docs/fmea.csv` - edit the CSV, not this file._", "",
           "Scale 1-10 (10 = worst). **S**everity of the effect, **O**ccurrence likelihood, **D**etection difficulty "
           "(10 = would go unnoticed). RPN = S x O x D. *Before* = no dedicated detection; *after* = current design, "
           "verified by the listed scenarios/requirements. Ranked by RPN before mitigation.", "",
           "| Rank | ID | Failure mode | Effect | S | O | D before | RPN before | Mitigation | Verified by | D after | RPN after | Status |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        ver = ", ".join(x for x in (r["scenario"].replace(";", ", "), r["requirement"].replace(";", ", ")) if x)
        out.append(f"| {i} | {r['id']} | {r['failure_mode']} | {r['effect']} | {r['S']} | {r['O']} | {r['D_before']} | "
                   f"**{r['rpn_before']}** | {r['mitigation']} | {ver} | {r['D_after']} | **{r['rpn_after']}** | {r['status']} |")
    open_rows = [r for r in rows if r["status"] != "mitigated"]
    out += ["", f"**Total RPN: {total_b} -> {total_a} ({100 * (total_b - total_a) / total_b:.0f} % reduction).** "
            f"Open items: {', '.join(r['id'] for r in open_rows) or 'none'}.", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rows = load()
    errors = validate(rows)
    rendered = render(rows)
    target = ROOT / "docs" / "fmea.md"
    if args.check and (not target.exists() or target.read_text(encoding="utf-8") != rendered):
        errors.append("docs/fmea.md is out of date - run tools/fmea.py")
    for e in errors:
        print("FMEA ERROR:", e, file=sys.stderr)
    if errors:
        return 1
    if not args.check:
        target.write_text(rendered, encoding="utf-8")
        print(f"wrote {target.relative_to(ROOT)}")
    else:
        print(f"{len(rows)} failure modes OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
