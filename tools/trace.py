#!/usr/bin/env python3
"""Requirements -> test traceability.

Reads requirement ids from docs/requirements.md (table rows starting with `| REQ-`) and
`// Verifies: REQ-A, REQ-B` tags placed directly above gtest TEST/TEST_P declarations, then writes
docs/traceability.md. With --check, exits non-zero when a requirement has no test or a test cites
an unknown requirement.
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ_RE = re.compile(r"^\|\s*(REQ-[A-Z]+-\d+)\s*\|\s*(.*?)\s*\|", re.M)
TAG_RE = re.compile(r"//\s*Verifies:\s*(.+)")
TEST_RE = re.compile(r"^\s*TEST(?:_P|_F)?\(\s*(\w+)\s*,\s*(\w+)\s*\)")


def read_requirements():
    text = (ROOT / "docs" / "requirements.md").read_text(encoding="utf-8")
    return {m.group(1): m.group(2) for m in REQ_RE.finditer(text)}


CMAKE_TEST_RE = re.compile(r"add_test\(\s*NAME\s+(\w+)")
YAML_JOB_RE = re.compile(r"^  ([\w-]+):\s*$")


def read_other_evidence(mapping):
    """`# Verifies:` tags above add_test() in CMake or above a job in the CI workflow."""
    sources = [(ROOT / "tests" / "CMakeLists.txt", CMAKE_TEST_RE, "ctest"),
               (ROOT / ".github" / "workflows" / "ci.yml", YAML_JOB_RE, "CI job")]
    for path, rx, kind in sources:
        if not path.exists():
            continue
        pending = []
        for line in path.read_text(encoding="utf-8").splitlines():
            tag = re.search(r"#\s*Verifies:\s*(.+)", line)
            if tag:
                pending = [r.strip() for r in tag.group(1).split(",") if r.strip()]
                continue
            m = rx.search(line)
            if m:
                for req in pending:
                    mapping[req].append((path.name, f"{kind} {m.group(1)}"))
                pending = []
            elif line.strip() and not line.strip().startswith("#"):
                pending = [] if not pending else pending


def read_tests():
    """Returns {req_id: [(file, suite.name), ...]}"""
    mapping = defaultdict(list)
    read_other_evidence(mapping)
    for path in sorted((ROOT / "tests").glob("test_*.cpp")):
        pending = []
        for line in path.read_text(encoding="utf-8").splitlines():
            tag = TAG_RE.search(line)
            if tag:
                pending = [r.strip() for r in tag.group(1).split(",") if r.strip()]
                continue
            m = TEST_RE.match(line)
            if m:
                for req in pending:
                    mapping[req].append((path.name, f"{m.group(1)}.{m.group(2)}"))
                pending = []
            elif line.strip() and not line.strip().startswith("//"):
                pending = []
    return mapping


def render(reqs, tests):
    out = ["# Requirements-to-test traceability matrix", "",
           "_Generated by `tools/trace.py` from `docs/requirements.md` and the `// Verifies:` tags in `tests/`. "
           "Do not edit by hand; CI fails if it is out of date or a requirement has no test._", "",
           "| Requirement | Description | Verified by | # tests |", "|---|---|---|---|"]
    for rid, desc in reqs.items():
        cases = tests.get(rid, [])
        names = "<br>".join(f"`{t}` ({f})" for f, t in sorted(set(cases))[:6])
        if len(set(cases)) > 6:
            names += f"<br>... +{len(set(cases)) - 6} more"
        short = desc if len(desc) < 110 else desc[:107] + "..."
        out.append(f"| {rid} | {short} | {names or '**NONE**'} | {len(set(cases))} |")
    covered = sum(1 for r in reqs if tests.get(r))
    out += ["", f"**Coverage: {covered}/{len(reqs)} requirements have at least one verifying test.**", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    reqs, tests = read_requirements(), read_tests()
    problems = [f"{r}: no verifying test" for r in reqs if not tests.get(r)]
    problems += [f"tests cite unknown requirement {r}" for r in tests if r not in reqs]
    rendered = render(reqs, tests)
    target = ROOT / "docs" / "traceability.md"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != rendered:
            problems.append("docs/traceability.md is out of date - run tools/trace.py")
        for p in problems:
            print("TRACE ERROR:", p, file=sys.stderr)
        print(f"{len(reqs)} requirements, {sum(1 for r in reqs if tests.get(r))} covered")
        return 1 if problems else 0
    target.write_text(rendered, encoding="utf-8")
    for p in problems:
        print("WARNING:", p, file=sys.stderr)
    print(f"wrote {target.relative_to(ROOT)}: {len(reqs)} requirements")
    return 0


if __name__ == "__main__":
    sys.exit(main())
